//
// НЕГА КЕРАК: платёжкада сумма ИККИ марта ёзилади — рақамда ва сўзда.
// AI рақамни адашиб ўқиши мумкин (2026-09-12: «100 000 000» ни
// «10 000 000 000» деб ўқиди — иккита ортиқча ноль). Сўздаги ёзув эса
// «бир юз миллион сўм» — бунда ноль йўқ, шунинг учун OCR камдан-кам
// адашади. Банкларда ҳам ҲУҚУҚИЙ жиҳатдан СЎЗДАГИСИ асосий ҳисобланади.
//
// Ўзбекча (лотин ва кирилл) ва русча ёзувни тушунади:
//   «бир юз миллион сўм»              → 100 000 000
//   «сто миллионов сум»               → 100 000 000
//   «yigirma bir million olti yuz…»   → 21 6xx xxx
