// Каррали сўзлар: ўзидан олдинги сонга кўпайтирилади
const KARRA = [
  [/^(миллиард|milliard|млрд|mlrd|миллиарда|миллиардов)$/, 1e9],
  [/^(миллион|million|млн|mln|миллиона|миллионов)$/, 1e6],
  [/^(минг|ming|тыс|тысяч|тысяча|тысячи|тысячу)$/, 1e3],
];

/** «бир юз миллион» → 100000000. Тушунмаса 0 қайтаради. */
export function sozdanSumma(matn) {
  const sozlar = String(matn || "")
    .toLowerCase()
    // Лотин ўзбекчада апостроф сўз ИЧИДА: «to'qson», «o'n», «to'rt». Аввал
    // у бўшлиққа айланиб «to qson» бўлиб қоларди → 90 йўқоларди
    // (2026-09-15: «besh million to'qson besh ming» → 5 005 000).
    .replace(/['ʻʼ’‘`]/g, "")
    .replace(/[«»"(),.:;]/g, " ")
    .replace(/ў/g, "ў").replace(/қ/g, "қ")
    .split(/[\s-]+/)
    .filter(Boolean);
  if (!sozlar.length) return 0;

  let jami = 0;      // тўпланган тўлиқ сумма
  let joriy = 0;     // ҳозирги гуруҳ (масалан «бир юз йигирма»)
  let borми = false;

  for (const xom of sozlar) {
    const soz = xom.replace(/[^\p{L}\p{N}]/gu, "");
    if (!soz) continue;

    // тийин бошланса — тўхтаймиз («… сўм 00 тийин»)
    if (/^(тийин|tiyin|коп|копеек|копейки|копейка)$/.test(soz)) break;

    const birlik = BIRLIK[soz];
    if (birlik !== undefined) {
      borми = true;
      if (birlik === 100) joriy = (joriy || 1) * 100;
      else joriy += birlik;
      continue;
    }

    let karra = 0;
    for (const [re, qiymat] of KARRA) if (re.test(soz)) { karra = qiymat; break; }
    if (karra) {
      // «миллион» дан ОЛДИН сон сўзи бўлиши ШАРТ. Акс ҳолда фирма номи
      // ҳам сумма бўлиб ўқиларди: «MILLION SAVDO MCHJ» → 1 000 000.
      if (!joriy) return 0;
      borми = true;
      jami += joriy * karra;
      joriy = 0;
      continue;
    }
    // «сўм», «sum», «uzs» ва бошқа сўзлар — эътиборсиз
  }
  if (!borми) return 0;
  const natija = Math.round(jami + joriy);
  // Тўлов ҳеч қачон 1 000 сўмдан кам бўлмайди. «бир», «юз» каби ёлғиз
  // сўзлар (фирма номидан) сумма деб қабул қилинмайди.
  return natija >= 1000 ? natija : 0;
}
